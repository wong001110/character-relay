const dictionaries: Record<LanguageCode, Record<TranslationKey, string>> = {
  en: english,
  "zh-CN": simplifiedChinese
};

const STORAGE_KEY = "echo-masque-language";

function interpolate(template: string, values?: Values): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  );
}

export function normalizeLanguage(value: string | null | undefined): LanguageCode {
  return value === "zh-CN" ? "zh-CN" : "en";
}

export function translate(
  language: LanguageCode,
  key: TranslationKey,
  values?: Values
): string {
  return interpolate(dictionaries[language][key] ?? english[key], values);
}

interface I18nValue {
  language: LanguageCode;
  setLanguage: (language: LanguageCode) => void;
  t: (key: TranslationKey, values?: Values) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<LanguageCode>(() => {
    if (typeof window === "undefined") return "en";
    return normalizeLanguage(window.localStorage.getItem(STORAGE_KEY));
  });

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const t = useCallback(
    (key: TranslationKey, values?: Values) => translate(language, key, values),
    [language]
  );
  const value = useMemo(() => ({ language, setLanguage, t }), [language, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
